@router.get(
    "/documents/{document_id}/download",
    summary="Download an authorised document",
    description=(
        "Authorised against the active company *and* the linked business entity. "
        "The stored digest is verified before any byte is returned; a corrupted "
        "file raises 409 rather than serving unverified content."
    ),
    responses={
        200: {"content": {"application/octet-stream": {}}},
        404: {"model": ErrorEnvelope, "description": "Unknown document."},
        409: {"model": ErrorEnvelope, "description": "Archived or corrupted file."},
    },
)
def download_document(
    document_id: UUID,
    context: Annotated[
        SessionContext, Depends(require_company_permission(Permission.COMPANY_VIEW))
    ],
    service: Annotated[DocumentService, Depends(get_document_service)],
    database: Annotated[Database, Depends(get_database)],
    request: Request,
) -> Response:
    meta = write_meta(context, request)
    with database.transaction() as session:
        download = service.download(session, meta=meta, document_id=document_id)
    headers = {
        "Content-Disposition": _content_disposition(download.record.original_filename),
        "Content-Length": str(len(download.content)),
        "Cache-Control": "no-store",
        "X-Content-Type-Options": "nosniff",
        "Vary": "Cookie",
        "X-Document-SHA256": download.record.sha256,
    }
    return Response(
        content=download.content,
        media_type=download.record.mime_type,
        headers=headers,
    )


