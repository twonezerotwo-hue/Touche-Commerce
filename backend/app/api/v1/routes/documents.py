@router.post(
    "/documents/{document_id}/archive",
    response_model=DocumentResponse,
    summary="Archive a document version (controlled, never a silent delete)",
    responses={409: {"model": ErrorEnvelope, "description": "Already archived."}},
)
def archive_document(
    document_id: UUID,
    payload: DocumentArchiveRequest,
    request: Request,
    response: Response,
    context: Annotated[
        SessionContext, Depends(require_company_permission(Permission.TRADE_WRITE))
    ],
    service: Annotated[DocumentService, Depends(get_document_service)],
    database: Annotated[Database, Depends(get_database)],
    settings: Annotated[Settings, Depends(app_settings)],
) -> DocumentResponse | JSONResponse:
    meta = write_meta(context, request)
    with idempotent_call(database, settings, context, request, payload) as call:
        if call.replay is not None:
            return replay_response(call.replay)
        record = service.archive(
            call.session, meta=meta, document_id=document_id, reason=payload.reason
        )
        body = document_response(record)
        call.complete(status_code=200, body=body.model_dump(mode="json"))
    response.headers["Cache-Control"] = "no-store"
    return body


