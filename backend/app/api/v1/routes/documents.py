"""Trade document routes: private upload, authorised download and honest previews.

The upload is the only endpoint that accepts a body that is not JSON. The file is
spooled to a bounded temporary stream so the SHA-256 and the size can be computed
*before* the idempotency fingerprint is taken: replaying the same key with a
different file is therefore an ``IDEMPOTENCY_CONFLICT`` rather than a silent
second version.

Nothing here trusts a client path. The storage key is generated by
:class:`~app.services.documents.DocumentStorage`, the download filename is
re-sanitised from the stored metadata, and both the company and the linked
business entity are re-authorised on every read.
"""

