@router.post(
    "/documents",
    response_model=DocumentResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Upload a document version to private storage",
    description=(
        "Multipart upload. The server generates the storage key, recomputes the "
        "SHA-256 while writing, rejects unsupported content types and enforces "
        "the size ceiling during the stream. A new upload for the same entity and "
        "document type becomes the next version and archives the previous one."
    ),
    responses={
        400: {"model": ErrorEnvelope, "description": "Unsupported type or bad link."},
        413: {"model": ErrorEnvelope, "description": "Upload exceeds the size limit."},
        409: {"model": ErrorEnvelope, "description": "Idempotency or version conflict."},
    },
)
def upload_document(
    request: Request,
    response: Response,
    context: Annotated[
        SessionContext, Depends(require_company_permission(Permission.TRADE_WRITE))
    ],
    service: Annotated[DocumentService, Depends(get_document_service)],
    database: Annotated[Database, Depends(get_database)],
    settings: Annotated[Settings, Depends(app_settings)],
    file: Annotated[UploadFile, File(description="The document file to store.")],
    document_type: Annotated[DocumentTypeValue, Form()],
    linked_entity_type: Annotated[LinkedEntityTypeValue, Form()],
    linked_entity_id: Annotated[UUID, Form()],
    title: Annotated[str | None, Form(max_length=200)] = None,
    supersedes_document_id: Annotated[UUID | None, Form()] = None,
    is_draft: Annotated[bool, Form()] = False,
) -> DocumentResponse | JSONResponse:
    if not file.filename:
        raise BadRequestError("A filename is required.", details={"field": "file"})

    meta = write_meta(context, request)
    with tempfile.SpooledTemporaryFile(max_size=_SPOOL_MEMORY) as spool:
        sha256, size = _fill_spool(
            file.file, spool, max_bytes=service.storage.max_bytes
        )
        data = UploadData(
            document_type=document_type,
            linked_entity_type=linked_entity_type,
            linked_entity_id=linked_entity_id,
            title=title or file.filename,
            filename=file.filename,
            mime_type=file.content_type or "application/octet-stream",
            supersedes_document_id=supersedes_document_id,
            is_draft=is_draft,
        )
        fingerprint_payload = {
            "document_type": document_type,
            "linked_entity_type": linked_entity_type,
            "linked_entity_id": str(linked_entity_id),
            "title": data.title,
            "filename": data.filename,
            "mime_type": data.mime_type,
            "supersedes_document_id": (
                str(supersedes_document_id) if supersedes_document_id else None
            ),
            "is_draft": is_draft,
            "sha256": sha256,
            "size_bytes": size,
        }
        with idempotent_call(
            database, settings, context, request, fingerprint_payload
        ) as call:
            if call.replay is not None:
                return replay_response(call.replay)
            record = service.upload(
                call.session,
                meta=meta,
                data=data,
                chunks=_spool_chunks(spool),
            )
            body = document_response(record)
            call.complete(status_code=201, body=body.model_dump(mode="json"))
    response.headers["ETag"] = etag_for(record.version)
    response.headers["Cache-Control"] = "no-store"
    return body


