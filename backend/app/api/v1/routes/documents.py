def _fill_spool(
    upload: BinaryIO, spool: tempfile.SpooledTemporaryFile[bytes], *, max_bytes: int
) -> tuple[str, int]:
    """Copy an upload into a bounded spool while hashing it.

    Memory stays bounded (large files spill to a temporary file) and an oversized
    body is rejected before a single row or storage key is created. The caller
    owns the spool so it is always closed by its context manager.
    """
    digest = hashlib.sha256()
    size = 0
    while True:
        chunk = upload.read(_CHUNK)
        if not chunk:
            break
        size += len(chunk)
        if size > max_bytes:
            raise PayloadTooLargeError(
                details={"max_bytes": max_bytes, "reason": "UPLOAD_TOO_LARGE"}
            )
        digest.update(chunk)
        spool.write(chunk)
    spool.seek(0)
    return digest.hexdigest(), size


def _spool_chunks(spool: tempfile.SpooledTemporaryFile[bytes]) -> Iterator[bytes]:
    while True:
        chunk = spool.read(_CHUNK)
        if not chunk:
            return
        yield chunk


def _content_disposition(filename: str) -> str:
    """ASCII-safe disposition plus the RFC 5987 form; never a raw client path."""
    safe = sanitise_filename(filename)
    ascii_name = safe.encode("ascii", "ignore").decode("ascii") or "document"
    return f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(safe)}"


